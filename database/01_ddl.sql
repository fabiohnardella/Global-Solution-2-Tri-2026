-- Notas de cada rota por perfil e período (cache recalculado a cada reporte/voto).
CREATE TABLE tb_avaliacao_rota (
  id_rota               NUMBER        NOT NULL,
  cd_perfil             VARCHAR2(20)  NOT NULL,
  tp_periodo            VARCHAR2(5)   NOT NULL,
  vl_acessibilidade     NUMBER(3)     NOT NULL,
  vl_seguranca          NUMBER(3)     NOT NULL,
  vl_geral              NUMBER(3)     NOT NULL,
  qt_trechos_criticos   NUMBER(2)     NOT NULL,
  vl_distancia_m        NUMBER(7)     NOT NULL,
  qt_duracao_min        NUMBER(4)     NOT NULL,
  dt_calculo            DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_avaliacao_rota PRIMARY KEY (id_rota, cd_perfil, tp_periodo),
  CONSTRAINT fk_aval_rota   FOREIGN KEY (id_rota)   REFERENCES tb_rota (id_rota) ON DELETE CASCADE,
  CONSTRAINT fk_aval_perfil FOREIGN KEY (cd_perfil) REFERENCES tb_perfil_mobilidade (cd_perfil),
  CONSTRAINT ck_aval_periodo CHECK (tp_periodo IN ('DIA', 'NOITE')),
  CONSTRAINT ck_aval_notas   CHECK (vl_acessibilidade BETWEEN 0 AND 100
                                    AND vl_seguranca BETWEEN 0 AND 100
                                    AND vl_geral BETWEEN 0 AND 100)
);

-- Indicadores diários por bairro (gerados pela procedure de indicadores).
CREATE TABLE tb_indicador_bairro (
  dt_referencia               DATE           NOT NULL,
  nm_bairro                   VARCHAR2(60)   NOT NULL,
  qt_alertas_ativos           NUMBER(6)      NOT NULL,
  qt_alertas_graves           NUMBER(6)      NOT NULL,
  qt_resolvidos_30d           NUMBER(6)      NOT NULL,
  vl_tempo_medio_resolucao_h  NUMBER(8,1),
  qt_pedidos_apoio_30d        NUMBER(6)      NOT NULL,
  cd_categoria_predominante   VARCHAR2(30),
  dt_geracao                  DATE           DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_indicador_bairro PRIMARY KEY (dt_referencia, nm_bairro),
  CONSTRAINT fk_ind_categoria FOREIGN KEY (cd_categoria_predominante)
    REFERENCES tb_categoria_barreira (cd_categoria)
);

