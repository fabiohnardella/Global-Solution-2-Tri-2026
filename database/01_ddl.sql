/* -----------------------------------------------------------------------------
   Limpeza (permite rodar o script várias vezes)
   ----------------------------------------------------------------------------- */
BEGIN
  FOR obj IN (
    SELECT object_name, object_type
      FROM user_objects
     WHERE object_name IN ('PKG_ROTAS_ACESSIVEIS',
                           'VW_ALERTAS_ATIVOS', 'VW_RANKING_ROTAS', 'VW_PEDIDOS_EM_ABERTO')
       AND object_type IN ('PACKAGE', 'VIEW')
  ) LOOP
    EXECUTE IMMEDIATE 'DROP ' || obj.object_type || ' ' || obj.object_name;
  END LOOP;

  FOR t IN (
    SELECT table_name
      FROM user_tables
     WHERE table_name IN ('TB_INDICADOR_BAIRRO', 'TB_AVALIACAO_ROTA', 'TB_PEDIDO_APOIO',
                          'TB_HISTORICO_ALERTA', 'TB_VOTO_ALERTA', 'TB_ALERTA',
                          'TB_ROTA_TRECHO', 'TB_ROTA', 'TB_TRECHO', 'TB_LOCAL',
                          'TB_CIDADAO', 'TB_PERFIL_SENSIBILIDADE', 'TB_GRAVIDADE',
                          'TB_CATEGORIA_BARREIRA', 'TB_PERFIL_MOBILIDADE')
  ) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

/* =============================================================================
   1. TABELAS DE DOMÍNIO (catálogos)
   ============================================================================= */

CREATE TABLE tb_perfil_mobilidade (
  cd_perfil               VARCHAR2(20)  NOT NULL,
  nm_perfil               VARCHAR2(60)  NOT NULL,
  ds_perfil               VARCHAR2(200),
  vl_velocidade_mps       NUMBER(4,2)   NOT NULL,
  vl_peso_rampa           NUMBER(4,2)   NOT NULL,
  vl_peso_piso_tatil      NUMBER(4,2)   NOT NULL,
  vl_peso_largura         NUMBER(4,2)   NOT NULL,
  vl_peso_inclinacao      NUMBER(4,2)   NOT NULL,
  vl_peso_acessibilidade  NUMBER(4,2)   NOT NULL,
  vl_inclinacao_max_pct   NUMBER(5,2)   NOT NULL,
  vl_largura_min_m        NUMBER(4,2)   NOT NULL,
  CONSTRAINT pk_perfil_mobilidade PRIMARY KEY (cd_perfil),
  CONSTRAINT ck_perfil_velocidade CHECK (vl_velocidade_mps > 0),
  CONSTRAINT ck_perfil_peso_acess CHECK (vl_peso_acessibilidade BETWEEN 0 AND 1),
  CONSTRAINT ck_perfil_pesos      CHECK (vl_peso_rampa + vl_peso_piso_tatil
                                         + vl_peso_largura + vl_peso_inclinacao > 0)
);

CREATE TABLE tb_categoria_barreira (
  cd_categoria               VARCHAR2(30)  NOT NULL,
  nm_categoria               VARCHAR2(60)  NOT NULL,
  ds_categoria               VARCHAR2(200),
  vl_impacto_acessibilidade  NUMBER(3,2)   NOT NULL,
  vl_impacto_seguranca       NUMBER(3,2)   NOT NULL,
  CONSTRAINT pk_categoria_barreira PRIMARY KEY (cd_categoria),
  CONSTRAINT ck_categoria_imp_acess CHECK (vl_impacto_acessibilidade BETWEEN 0 AND 1),
  CONSTRAINT ck_categoria_imp_seg   CHECK (vl_impacto_seguranca BETWEEN 0 AND 1)
);

CREATE TABLE tb_gravidade (
  cd_gravidade         VARCHAR2(10)  NOT NULL,
  nm_gravidade         VARCHAR2(20)  NOT NULL,
  ds_gravidade         VARCHAR2(200),
  nr_ordem             NUMBER(1)     NOT NULL,
  vl_peso_relevancia   NUMBER(5,2)   NOT NULL,
  vl_penalidade        NUMBER(5,2)   NOT NULL,
  CONSTRAINT pk_gravidade PRIMARY KEY (cd_gravidade),
  CONSTRAINT uk_gravidade_ordem UNIQUE (nr_ordem),
  CONSTRAINT ck_gravidade_peso CHECK (vl_peso_relevancia BETWEEN 0 AND 100),
  CONSTRAINT ck_gravidade_penal CHECK (vl_penalidade >= 0)
);

-- Associativa PERFIL x CATEGORIA: quanto cada barreira pesa para cada perfil.
CREATE TABLE tb_perfil_sensibilidade (
  cd_perfil         VARCHAR2(20)  NOT NULL,
  cd_categoria      VARCHAR2(30)  NOT NULL,
  vl_multiplicador  NUMBER(3,2)   NOT NULL,
  CONSTRAINT pk_perfil_sensibilidade PRIMARY KEY (cd_perfil, cd_categoria),
  CONSTRAINT fk_sens_perfil    FOREIGN KEY (cd_perfil)    REFERENCES tb_perfil_mobilidade (cd_perfil),
  CONSTRAINT fk_sens_categoria FOREIGN KEY (cd_categoria) REFERENCES tb_categoria_barreira (cd_categoria),
  CONSTRAINT ck_sens_mult CHECK (vl_multiplicador > 0)
);

