CREATE TABLE tb_local (
  id_local         NUMBER GENERATED BY DEFAULT AS IDENTITY,
  cd_local         VARCHAR2(20)   NOT NULL,
  nm_local         VARCHAR2(100)  NOT NULL,
  nm_curto         VARCHAR2(40)   NOT NULL,
  ds_endereco      VARCHAR2(150)  NOT NULL,
  nm_bairro        VARCHAR2(60)   NOT NULL,
  vl_latitude      NUMBER(9,6)    NOT NULL,
  vl_longitude     NUMBER(9,6)    NOT NULL,
  ds_dica_chegada  VARCHAR2(200),
  CONSTRAINT pk_local PRIMARY KEY (id_local),
  CONSTRAINT uk_local_codigo UNIQUE (cd_local),
  CONSTRAINT ck_local_lat CHECK (vl_latitude BETWEEN -90 AND 90),
  CONSTRAINT ck_local_lon CHECK (vl_longitude BETWEEN -180 AND 180)
);

CREATE TABLE tb_trecho (
  id_trecho                NUMBER GENERATED BY DEFAULT AS IDENTITY,
  cd_trecho                VARCHAR2(10)   NOT NULL,
  nm_logradouro            VARCHAR2(80)   NOT NULL,
  tp_trecho                VARCHAR2(10)   NOT NULL,
  ds_ponto_inicial         VARCHAR2(80)   NOT NULL,
  ds_ponto_final           VARCHAR2(80)   NOT NULL,
  nm_bairro                VARCHAR2(60)   NOT NULL,
  vl_distancia_m           NUMBER(6)      NOT NULL,
  qt_duracao_fixa_min      NUMBER(3),
  vl_cobertura_rampa       NUMBER(3,2)    NOT NULL,
  vl_cobertura_piso_tatil  NUMBER(3,2)    NOT NULL,
  vl_largura_calcada_m     NUMBER(4,2)    NOT NULL,
  vl_inclinacao_pct        NUMBER(4,2)    NOT NULL,
  vl_iluminacao            NUMBER(3,2)    NOT NULL,
  vl_fluxo_pedestres       NUMBER(3,2)    NOT NULL,
  qt_ocorrencias_90d       NUMBER(4)      DEFAULT 0 NOT NULL,
  ds_orientacao            VARCHAR2(300),
  CONSTRAINT pk_trecho PRIMARY KEY (id_trecho),
  CONSTRAINT uk_trecho_codigo UNIQUE (cd_trecho),
  CONSTRAINT ck_trecho_tipo      CHECK (tp_trecho IN ('CALCADA', 'CALCADAO', 'TRAVESSIA', 'METRO')),
  CONSTRAINT ck_trecho_distancia CHECK (vl_distancia_m > 0),
  CONSTRAINT ck_trecho_duracao   CHECK (qt_duracao_fixa_min IS NULL OR qt_duracao_fixa_min > 0),
  CONSTRAINT ck_trecho_rampa     CHECK (vl_cobertura_rampa BETWEEN 0 AND 1),
  CONSTRAINT ck_trecho_tatil     CHECK (vl_cobertura_piso_tatil BETWEEN 0 AND 1),
  CONSTRAINT ck_trecho_largura   CHECK (vl_largura_calcada_m > 0),
  CONSTRAINT ck_trecho_inclin    CHECK (vl_inclinacao_pct >= 0),
  CONSTRAINT ck_trecho_ilum      CHECK (vl_iluminacao BETWEEN 0 AND 1),
  CONSTRAINT ck_trecho_fluxo     CHECK (vl_fluxo_pedestres BETWEEN 0 AND 1),
  CONSTRAINT ck_trecho_ocorr     CHECK (qt_ocorrencias_90d >= 0)
);

CREATE INDEX ix_trecho_bairro ON tb_trecho (nm_bairro);

CREATE TABLE tb_rota (
  id_rota           NUMBER GENERATED BY DEFAULT AS IDENTITY,
  cd_rota           VARCHAR2(10)   NOT NULL,
  nm_rota           VARCHAR2(80)   NOT NULL,
  ds_resumo         VARCHAR2(200),
  id_local_origem   NUMBER         NOT NULL,
  id_local_destino  NUMBER         NOT NULL,
  CONSTRAINT pk_rota PRIMARY KEY (id_rota),
  CONSTRAINT uk_rota_codigo UNIQUE (cd_rota),
  CONSTRAINT fk_rota_origem  FOREIGN KEY (id_local_origem)  REFERENCES tb_local (id_local),
  CONSTRAINT fk_rota_destino FOREIGN KEY (id_local_destino) REFERENCES tb_local (id_local),
  CONSTRAINT ck_rota_origem_destino CHECK (id_local_origem <> id_local_destino)
);

CREATE INDEX ix_rota_origem_destino ON tb_rota (id_local_origem, id_local_destino);

-- Associativa ROTA x TRECHO (N:N com atributos de ordem e sentido).
CREATE TABLE tb_rota_trecho (
  id_rota             NUMBER     NOT NULL,
  nr_ordem            NUMBER(2)  NOT NULL,
  id_trecho           NUMBER     NOT NULL,
  st_sentido_inverso  CHAR(1)    DEFAULT 'N' NOT NULL,
  CONSTRAINT pk_rota_trecho PRIMARY KEY (id_rota, nr_ordem),
  CONSTRAINT fk_rt_rota   FOREIGN KEY (id_rota)   REFERENCES tb_rota (id_rota) ON DELETE CASCADE,
  CONSTRAINT fk_rt_trecho FOREIGN KEY (id_trecho) REFERENCES tb_trecho (id_trecho),
  CONSTRAINT ck_rt_ordem   CHECK (nr_ordem > 0),
  CONSTRAINT ck_rt_sentido CHECK (st_sentido_inverso IN ('S', 'N'))
);

CREATE INDEX ix_rota_trecho_trecho ON tb_rota_trecho (id_trecho);

/* =============================================================================
   4. PARTICIPAÇÃO CIDADÃ: ALERTAS, VOTOS E HISTÓRICO
   ============================================================================= */

CREATE TABLE tb_alerta (
  id_alerta              NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_trecho              NUMBER         NOT NULL,
  cd_categoria           VARCHAR2(30)   NOT NULL,
  cd_gravidade           VARCHAR2(10)   NOT NULL,
  id_cidadao_autor       NUMBER         NOT NULL,
  ds_referencia          VARCHAR2(120)  NOT NULL,
  ds_descricao           VARCHAR2(280),
  dt_criacao             DATE           DEFAULT SYSDATE NOT NULL,
  dt_atualizacao         DATE           DEFAULT SYSDATE NOT NULL,
  dt_ultima_confirmacao  DATE           DEFAULT SYSDATE NOT NULL,
  qt_confirmacoes        NUMBER(5)      DEFAULT 1 NOT NULL,
  qt_votos_resolvido     NUMBER(5)      DEFAULT 0 NOT NULL,
  st_alerta              VARCHAR2(10)   DEFAULT 'ATIVO' NOT NULL,
  dt_resolucao           DATE,
  vl_relevancia          NUMBER(3)      DEFAULT 0 NOT NULL,
  CONSTRAINT pk_alerta PRIMARY KEY (id_alerta),
  CONSTRAINT fk_alerta_trecho    FOREIGN KEY (id_trecho)        REFERENCES tb_trecho (id_trecho),
  CONSTRAINT fk_alerta_categoria FOREIGN KEY (cd_categoria)     REFERENCES tb_categoria_barreira (cd_categoria),
  CONSTRAINT fk_alerta_gravidade FOREIGN KEY (cd_gravidade)     REFERENCES tb_gravidade (cd_gravidade),
  CONSTRAINT fk_alerta_autor     FOREIGN KEY (id_cidadao_autor) REFERENCES tb_cidadao (id_cidadao),
  CONSTRAINT ck_alerta_status    CHECK (st_alerta IN ('ATIVO', 'RESOLVIDO')),
  CONSTRAINT ck_alerta_conf      CHECK (qt_confirmacoes >= 0),
  CONSTRAINT ck_alerta_votos     CHECK (qt_votos_resolvido >= 0),
  CONSTRAINT ck_alerta_relev     CHECK (vl_relevancia BETWEEN 0 AND 100),
  CONSTRAINT ck_alerta_ref       CHECK (LENGTH(TRIM(ds_referencia)) >= 3),
  CONSTRAINT ck_alerta_resolucao CHECK (
    (st_alerta = 'ATIVO' AND dt_resolucao IS NULL) OR
    (st_alerta = 'RESOLVIDO' AND dt_resolucao IS NOT NULL)
  )
);

CREATE INDEX ix_alerta_trecho_status ON tb_alerta (id_trecho, st_alerta);
CREATE INDEX ix_alerta_categoria     ON tb_alerta (cd_categoria);
CREATE INDEX ix_alerta_autor         ON tb_alerta (id_cidadao_autor);

-- Um voto por cidadão por alerta (regra de validação comunitária).
CREATE TABLE tb_voto_alerta (
  id_voto     NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_alerta   NUMBER        NOT NULL,
  id_cidadao  NUMBER        NOT NULL,
  tp_voto     VARCHAR2(10)  NOT NULL,
  dt_voto     DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_voto_alerta PRIMARY KEY (id_voto),
  CONSTRAINT uk_voto_alerta_cidadao UNIQUE (id_alerta, id_cidadao),
  CONSTRAINT fk_voto_alerta  FOREIGN KEY (id_alerta)  REFERENCES tb_alerta (id_alerta) ON DELETE CASCADE,
  CONSTRAINT fk_voto_cidadao FOREIGN KEY (id_cidadao) REFERENCES tb_cidadao (id_cidadao),
  CONSTRAINT ck_voto_tipo CHECK (tp_voto IN ('CONFIRMOU', 'RESOLVEU'))
);

CREATE INDEX ix_voto_cidadao ON tb_voto_alerta (id_cidadao);

-- Auditoria automática (preenchida por trigger).
CREATE TABLE tb_historico_alerta (
  id_historico            NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_alerta               NUMBER         NOT NULL,
  tp_evento               VARCHAR2(20)   NOT NULL,
  st_anterior             VARCHAR2(10),
  st_novo                 VARCHAR2(10),
  cd_gravidade_anterior   VARCHAR2(10),
  cd_gravidade_nova       VARCHAR2(10),
  qt_confirmacoes         NUMBER(5),
  qt_votos_resolvido      NUMBER(5),
  dt_evento               DATE           DEFAULT SYSDATE NOT NULL,
  nm_usuario_bd           VARCHAR2(128)  DEFAULT USER NOT NULL,
  -- Sem FK proposital: a trilha de auditoria sobrevive mesmo se o alerta for excluído.
  CONSTRAINT pk_historico_alerta PRIMARY KEY (id_historico),
  CONSTRAINT ck_hist_evento CHECK (tp_evento IN ('CRIACAO', 'CONFIRMACAO', 'VOTO_RESOLVIDO',
                                                 'RESOLUCAO', 'REABERTURA', 'ALTERACAO_GRAVIDADE'))
);

CREATE INDEX ix_hist_alerta ON tb_historico_alerta (id_alerta, dt_evento);

/* =============================================================================
   5. APOIO AO CIDADÃO (botão "Alerta Rápido" do modo navegação)
   ============================================================================= */

CREATE TABLE tb_pedido_apoio (
  id_pedido               NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_cidadao              NUMBER         NOT NULL,
  id_rota                 NUMBER,
  id_trecho               NUMBER,
  tp_pedido               VARCHAR2(10)   NOT NULL,
  ds_localizacao          VARCHAR2(200)  NOT NULL,
  st_atendimento          VARCHAR2(15)   DEFAULT 'ABERTO' NOT NULL,
  dt_pedido               DATE           DEFAULT SYSDATE NOT NULL,
  dt_inicio_atendimento   DATE,
  dt_conclusao            DATE,
  ds_observacao           VARCHAR2(300),
  CONSTRAINT pk_pedido_apoio PRIMARY KEY (id_pedido),
  CONSTRAINT fk_pedido_cidadao FOREIGN KEY (id_cidadao) REFERENCES tb_cidadao (id_cidadao),
  CONSTRAINT fk_pedido_rota    FOREIGN KEY (id_rota)    REFERENCES tb_rota (id_rota),
  CONSTRAINT fk_pedido_trecho  FOREIGN KEY (id_trecho)  REFERENCES tb_trecho (id_trecho),
  CONSTRAINT ck_pedido_tipo    CHECK (tp_pedido IN ('APOIO', 'EMERGENCIA')),
  CONSTRAINT ck_pedido_status  CHECK (st_atendimento IN ('ABERTO', 'EM_ATENDIMENTO', 'CONCLUIDO', 'CANCELADO')),
  CONSTRAINT ck_pedido_datas   CHECK (dt_conclusao IS NULL OR dt_conclusao >= dt_pedido)
);

CREATE INDEX ix_pedido_status ON tb_pedido_apoio (st_atendimento, dt_pedido);

