  vl_velocidade_fala  NUMBER(3,2)   DEFAULT 0.95 NOT NULL,
  st_alto_contraste   CHAR(1)       DEFAULT 'N' NOT NULL,
  st_texto_grande     CHAR(1)       DEFAULT 'N' NOT NULL,
  dt_cadastro         DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_cidadao PRIMARY KEY (id_cidadao),
  CONSTRAINT fk_cidadao_perfil FOREIGN KEY (cd_perfil) REFERENCES tb_perfil_mobilidade (cd_perfil),
  CONSTRAINT ck_cidadao_voz        CHECK (st_voz_ativa IN ('S', 'N')),
  CONSTRAINT ck_cidadao_contraste  CHECK (st_alto_contraste IN ('S', 'N')),
  CONSTRAINT ck_cidadao_texto      CHECK (st_texto_grande IN ('S', 'N')),
  CONSTRAINT ck_cidadao_vel_fala   CHECK (vl_velocidade_fala BETWEEN 0.5 AND 1.5)
);

